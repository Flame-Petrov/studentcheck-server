-- StudentCheck database schema (v2).
--
-- Conventions
--   * snake_case, plural table names, "<entity>_id" foreign keys
--   * bigint identity primary keys
--   * every point in time is timestamptz
--   * lookup tables (degrees, attendance_statuses) are keyed by a readable code
--   * nothing is stored that can be counted: lesson and attendance totals come
--     from lessons / attendance_records (see student_course_attendance)
--
-- Apply to an empty "public" schema:  psql "$DATABASE_URL" -f db/schema.sql

BEGIN;

-- ---------- People ----------

-- Everyone who can log in. Teachers have no extra columns yet; students have a
-- profile row in "students". New roles only need a new value in the CHECK.
CREATE TABLE users (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role             text        NOT NULL CHECK (role IN ('teacher', 'student', 'admin')),
    full_name        text        NOT NULL,
    email_encrypted  text        NOT NULL,
    email_hash       text        NOT NULL UNIQUE,   -- HMAC of the normalized email, used for lookups
    password_hash    text        NOT NULL,          -- argon2id string; "legacy-v1:..." until the next login
    created_at       timestamptz NOT NULL DEFAULT now()
);

-- ---------- Academic structure (lookup data) ----------

CREATE TABLE degrees (
    code     text PRIMARY KEY,                      -- 'bachelor', 'master', 'phd'
    name_bg  text NOT NULL,
    name_en  text NOT NULL
);

CREATE TABLE faculties (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     text NOT NULL UNIQUE,                  -- 'economics'
    name_bg  text NOT NULL,
    name_en  text NOT NULL
);

-- A specialization offered by a faculty at one degree level.
CREATE TABLE programs (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id   bigint NOT NULL REFERENCES faculties (id),
    degree_code  text   NOT NULL REFERENCES degrees (code),
    code         text   NOT NULL UNIQUE,            -- 'bachelor-industrial-management'
    name_bg      text   NOT NULL,
    name_en      text   NOT NULL,
    UNIQUE (faculty_id, degree_code, name_en)
);

-- Student profile, one per student user.
CREATE TABLE students (
    user_id                   bigint   PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    faculty_number_encrypted  text     NOT NULL,
    faculty_number_hash       text     NOT NULL UNIQUE,
    program_id                bigint   NOT NULL REFERENCES programs (id),
    study_year                smallint NOT NULL CHECK (study_year BETWEEN 1 AND 6),
    group_number              smallint NOT NULL CHECK (group_number > 0)
);
CREATE INDEX idx_students_program ON students (program_id);

-- ---------- Teaching ----------

-- Called "classes" in the API and UI.
CREATE TABLE courses (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id  bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name        text        NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (teacher_id, name)
);

CREATE TABLE course_enrollments (
    course_id    bigint      NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
    student_id   bigint      NOT NULL REFERENCES students (user_id) ON DELETE CASCADE,
    enrolled_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (course_id, student_id)
);
CREATE INDEX idx_course_enrollments_student ON course_enrollments (student_id);

-- One attendance session (one press of "Finish" in the scanner).
CREATE TABLE lessons (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id          bigint      NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
    started_at         timestamptz,                 -- NULL only for migrated lessons whose date was never stored
    ended_at           timestamptz CHECK (ended_at >= started_at),
    client_session_id  text,                        -- scanner session id; a retried Finish reuses the lesson
    UNIQUE (course_id, client_session_id)
);
CREATE INDEX idx_lessons_course_started ON lessons (course_id, started_at);

-- ---------- Attendance ----------

CREATE TABLE attendance_statuses (
    code               text    PRIMARY KEY,         -- 'present', 'absent' (add 'late', 'excused', ... as rows)
    name_bg            text    NOT NULL,
    name_en            text    NOT NULL,
    counts_as_present  boolean NOT NULL
);

-- One row per student per lesson. History survives removing a student from a
-- course, because rows reference the student, not the enrollment.
CREATE TABLE attendance_records (
    lesson_id    bigint      NOT NULL REFERENCES lessons (id) ON DELETE CASCADE,
    student_id   bigint      NOT NULL REFERENCES students (user_id) ON DELETE CASCADE,
    status_code  text        NOT NULL REFERENCES attendance_statuses (code),
    joined_at    timestamptz,
    left_at      timestamptz CHECK (left_at >= joined_at),
    PRIMARY KEY (lesson_id, student_id)
);
CREATE INDEX idx_attendance_records_student ON attendance_records (student_id);

-- ---------- Billing ----------

CREATE TABLE billing_accounts (
    teacher_id              bigint PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    stripe_customer_id      text UNIQUE,
    stripe_subscription_id  text,
    plan                    text,
    subscription_status     text,
    current_period_end      timestamptz,
    updated_at              timestamptz NOT NULL DEFAULT now()
);

-- Stripe webhook idempotency.
CREATE TABLE stripe_events (
    event_id      text PRIMARY KEY,
    processed_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------- Derived numbers ----------

-- Lessons held and attended per student per course. security_invoker makes the
-- view obey the tables' RLS instead of its owner's rights.
CREATE VIEW student_course_attendance WITH (security_invoker = true) AS
SELECT
    l.course_id,
    ar.student_id,
    count(*)::integer                                    AS lessons_total,
    (count(*) FILTER (WHERE st.counts_as_present))::integer AS lessons_attended
FROM attendance_records ar
JOIN lessons l              ON l.id = ar.lesson_id
JOIN attendance_statuses st ON st.code = ar.status_code
GROUP BY l.course_id, ar.student_id;

