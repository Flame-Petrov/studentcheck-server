-- ---------- Access ----------

-- Supabase exposes "public" through its REST API. Only the server (connecting
-- as the database owner) may touch these tables: RLS on, no policies.
ALTER TABLE users               ENABLE ROW LEVEL SECURITY;
ALTER TABLE degrees             ENABLE ROW LEVEL SECURITY;
ALTER TABLE faculties           ENABLE ROW LEVEL SECURITY;
ALTER TABLE programs            ENABLE ROW LEVEL SECURITY;
ALTER TABLE students            ENABLE ROW LEVEL SECURITY;
ALTER TABLE courses             ENABLE ROW LEVEL SECURITY;
ALTER TABLE course_enrollments  ENABLE ROW LEVEL SECURITY;
ALTER TABLE lessons             ENABLE ROW LEVEL SECURITY;
ALTER TABLE attendance_statuses ENABLE ROW LEVEL SECURITY;
ALTER TABLE attendance_records  ENABLE ROW LEVEL SECURITY;
ALTER TABLE billing_accounts    ENABLE ROW LEVEL SECURITY;
ALTER TABLE stripe_events       ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON student_course_attendance FROM anon, authenticated;
    END IF;
END $$;

COMMIT;
